export type CountryOption = { code: string; name: string; flag: string };

/** Alle lande sorteret efter dansk navn. */
export const COUNTRIES: readonly CountryOption[] = Object.entries(COUNTRY_NAMES_DA).map(
  ([code, name]) => ({ code, name, flag: flagEmoji(code) }),
);

export function countryName(code: string | null | undefined): string {
  if (!code) return "";
  return COUNTRY_NAMES_DA[code.toUpperCase()] ?? code.toUpperCase();
}

/** Flag-emoji ud fra landekoden (to "regional indicator"-tegn). */
export function flagEmoji(code: string): string {
  const cc = code.toUpperCase();
  if (!/^[A-Z]{2}$/.test(cc)) return "";
  return String.fromCodePoint(...[...cc].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65));
}

/** Flagene for en rejses lande, fx "🇮🇹 🇫🇷 🇪🇸 …". */
export function flagEmojis(codes: readonly string[], max = 3): string {
  const flags = codes.slice(0, max).map(flagEmoji).filter(Boolean).join(" ");
  return codes.length > max ? `${flags} …` : flags;
}

/** "Italien, Frankrig og Spanien" */
export function countryNames(codes: readonly string[]): string {
  const names = codes.map((c) => countryName(c));
  if (names.length <= 1) return names[0] ?? "";
  return `${names.slice(0, -1).join(", ")} og ${names[names.length - 1]}`;
}

/** Fakta om et land fra REST Countries (hentet via serveren og cachet lokalt). */
export type CountryFacts = {
  code: string;
  /** ISO 4217, fx ["EUR"] */
  currencies: string[];
  /** Danske sprognavne, fx ["italiensk"] */
  languages: string[];
  capital: string | null;
};

/** "Italien · EUR · italiensk" */
export function formatCountryFacts(code: string, facts?: CountryFacts | null): string {
  const parts = [countryName(code)];
  if (facts?.currencies.length) parts.push(facts.currencies.join("/"));
  if (facts?.languages.length) parts.push(facts.languages.slice(0, 2).join(", "));
  return parts.join(" · ");
}
